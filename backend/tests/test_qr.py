@pytest.mark.qr
def test_nothing_in_a_full_scan_touches_the_network(qr_samples, monkeypatch):
    """A QR payload is a URL chosen by a stranger. We read it; we never open it.

    Every outbound path funnels through the socket module, so poisoning it
    catches a request made through urllib, httpx, requests or a raw socket
    alike. The fixtures used here are the ones whose payloads most invite a
    lookup: off-allowlist hosts, a shortener, a userinfo trick, and a PDF
    carrying its own clickable link.
    """
    import socket

    attempts: list[str] = []

    def forbidden(name):
        def blocked(*args, **kwargs):
            attempts.append(name)
            raise AssertionError(f"network access attempted via {name}")

        return blocked

    for name in (
        "socket",
        "create_connection",
        "getaddrinfo",
        "gethostbyname",
        "gethostbyname_ex",
        "getfqdn",
        "create_server",
    ):
        if hasattr(socket, name):
            monkeypatch.setattr(socket, name, forbidden(f"socket.{name}"))

    # Prove the trap is armed before trusting it. Without this, the test
    # passes just as happily when the patching silently stops working.
    with pytest.raises(AssertionError, match="network access attempted"):
        socket.getaddrinfo("verify.nbta-demo.test", 443)
    attempts.clear()

    for key in (
        "valid_pdf",
        "qr_wrong_domain",
        "qr_shortener",
        "qr_userinfo",
        "qr_ip_host",
        "link_mismatch_pdf",
        "qr_punycode",
    ):
        result = scan(qr_samples[key])
        assert result.status in (QRStatus.OK, QRStatus.NO_QR_FOUND)

    assert attempts == []


