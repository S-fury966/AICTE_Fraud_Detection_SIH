def test_classify_distinguishes_urls_plain_text_and_other():
    assert classify("https://verify.nbta-demo.test/c/x") is PayloadKind.URL
    assert classify("http://verify.nbta-demo.test/c/x") is PayloadKind.URL
    assert classify(CERT_ID) is PayloadKind.PLAIN_TEXT
    assert classify("mailto:registrar@nbta-demo.test") is PayloadKind.OTHER
    assert classify("javascript:alert(1)") is PayloadKind.OTHER
    assert classify("") is PayloadKind.OTHER


def test_a_schemeless_host_is_plain_text_not_a_url():
    """Guessing a scheme would mean reporting a domain nobody wrote."""
    assert classify("verify.nbta-demo.test/c/123") is PayloadKind.PLAIN_TEXT


def test_url_parts_are_split_out():
    parsed = parse_url("https://user:pw@verify.nbta-demo.test:8443/c/abc?cert=XYZ")

    assert parsed.scheme == "https"
    assert parsed.host == "verify.nbta-demo.test"
    assert parsed.port == 8443
    assert parsed.userinfo == "user:pw"
    assert parsed.path == "/c/abc"
    assert parsed.query["cert"] == ["XYZ"]


def test_host_is_lowercased_and_the_root_dot_stripped():
    assert parse_url("https://VERIFY.NBTA-DEMO.TEST./c/x").host == GOOD_HOST


def test_punycode_host_is_decoded_and_flagged():
    parsed = parse_url("https://xn--80ak6aa92e.test/c/x")

    assert parsed.punycode is True
    assert parsed.host_raw == "xn--80ak6aa92e.test"
    # Compared as the characters it displays, not as its ASCII encoding.
    assert parsed.host != parsed.host_raw


def test_an_internationalised_host_with_an_ascii_tld_is_not_mixed_script():
    """Per-label, not per-host: every IDN pairs a non-Latin name with .in/.test."""
    assert parse_url("https://xn--11b4c3d.in/c/x").mixed_script is False


def test_a_homoglyph_inside_one_label_is_mixed_script():
    # Cyrillic 'а' inside an otherwise Latin word.
    assert parse_url("https://аpple.test/c/x").mixed_script is True


def test_ip_hosts_are_recognised():
    assert parse_url("https://192.0.2.77/c/x").ip_host is True
    assert parse_url("https://[2001:db8::1]/c/x").ip_host is True
    assert parse_url(f"https://{GOOD_HOST}/c/x").ip_host is False


def test_certificate_id_is_percent_decoded_from_the_path(qr_config):
    parsed = parse_url(verify_url())
    value, origin = extract_certificate_id(
        verify_url(), parsed, PayloadKind.URL, qr_config
    )

    assert value == CERT_ID
    assert origin == "path"


