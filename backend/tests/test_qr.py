def finding_types(result) -> list[str]:
    return [f.type.value for f in result.findings]


def finding_of(result, finding_type: FindingType):
    for finding in result.findings:
        if finding.type is finding_type:
            return finding
    raise AssertionError(
        f"no {finding_type.value} finding; got {finding_types(result)}"
    )


def scan(path, **kwargs):
    kwargs.setdefault("certificate_number", CERT_ID)
    kwargs.setdefault("issuing_body", ISSUER)
    kwargs.setdefault("compare_certificate_number", True)
    return scan_document(path, **kwargs)


